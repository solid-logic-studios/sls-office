/** Drawn for a character with no glyph, so the gap is visible. */
export const UNKNOWN_GLYPH: readonly string[] = ['#####', '#...#', '#...#', '#...#', '#...#', '#...#', '#####'];

function glyphOf(char: string): readonly string[] {
  return GLYPHS[char.toUpperCase()] ?? UNKNOWN_GLYPH;
}

/** Width in art pixels. Counts the gap after the last character, as the Painter's layout does. */
export function textWidth(text: string, bold = false): number {
  return [...text].length * (bold ? BOLD_ADVANCE : ADVANCE);
}

/** A glyph row as ink flags; bold smears each pixel one to the right. */
function inkOf(row: string, bold: boolean): boolean[] {
  const ink = Array.from(row, (cell) => cell === '#');
  if (!bold) return ink;
  return [...ink, false].map((on, col) => on || ink[col - 1] === true);
}

/**
 * Paints `text` with `fill`, one call per horizontal run of ink. `x` is the left edge; the bottom row
 * of each glyph sits on the row just above `baselineY`.
 */
export function drawText(
  fill: (x: number, y: number, w: number, h: number) => void,
  text: string,
  x: number,
  baselineY: number,
  bold = false,
): void {
  const advance = bold ? BOLD_ADVANCE : ADVANCE;
  let left = x;
  for (const char of text) {
    glyphOf(char).forEach((row, rowIndex) => {
      const y = baselineY - CAP_HEIGHT + rowIndex;
      const ink = inkOf(row, bold);
      let runStart = -1;
      for (let col = 0; col <= ink.length; col++) {
        if (ink[col] === true) {
          if (runStart < 0) runStart = col;
        } else if (runStart >= 0) {
          fill(left + runStart, y, col - runStart, 1);
          runStart = -1;
        }
      }
    });
    left += advance;
  }
}
